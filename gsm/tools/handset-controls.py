"""Export navigation hit regions and feedback from the final Blender masks.

Run after changing handset key geometry. The browser uses ordinary anchors and
CSS; no runtime geometry, duplicated glyphs or pointer-state synchronisation.
"""
import argparse
import json
from pathlib import Path

from PIL import Image, ImageChops, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tools" / "handset-source"
START = "/* BEGIN generated handset controls */"
END = "/* END generated handset controls */"


def export(orientation):
    geometry = json.loads((SOURCE / f"controls-{orientation}.json").read_text())
    image_width, image_height = geometry["logicalImageSize"]
    native_width, native_height = geometry["nativeSize"]
    margin = geometry["bodyMarginLogical"]
    rules, assets = [], {}
    for key in geometry["keys"]:
        mask = Image.open(SOURCE / key["mask"]).convert("L").point(lambda v: 255 if v > 127 else 0)
        x0, y0, x1, y1 = key["maskBoundsNative"]
        local = mask.crop((x0, y0, x1, y1))
        width, height = local.size
        rows = []
        for y in range(height):
            occupied = [x for x in range(width) if local.getpixel((x, y))]
            assert occupied and occupied == list(range(min(occupied), max(occupied) + 1))
            rows.append((min(occupied), max(occupied) + 1))
        points = []
        for y, (left, _) in enumerate(rows):
            points.extend(((left, y), (left, y + 1)))
        for y in reversed(range(height)):
            points.extend(((rows[y][1], y + 1), (rows[y][1], y)))
        simplified = []
        for point in points:
            if simplified and point == simplified[-1]:
                continue
            while len(simplified) >= 2:
                a, b = simplified[-2:]
                if (b[0] - a[0]) * (point[1] - b[1]) != (b[1] - a[1]) * (point[0] - b[0]):
                    break
                simplified.pop()
            simplified.append(point)
        polygon = ",".join(f"{x / width * 100:.4f}% {y / height * 100:.4f}%" for x, y in simplified)
        # Erode the full mask, before cropping, to keep feedback inside the cap.
        ring = ImageChops.subtract(mask, mask.filter(ImageFilter.MinFilter(3))).crop((x0, y0, x1, y1))
        path = "".join(f"M{x} {y}h1v1h-1z" for y in range(height) for x in range(width) if ring.getpixel((x, y)))
        filename = f"control-focus-{orientation}-{key['id']}.svg"
        assets[ROOT / "assets" / filename] = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" shape-rendering="crispEdges"><path fill="#e3ddca" fill-opacity=".82" d="{path}"/></svg>\n'
        rules.append(f"""#{key['id']}Button{{
  left:calc({image_width}rem * {x0} / {native_width} - {margin}rem);top:calc({image_height}rem * {y0} / {native_height} - {margin}rem);
  width:calc({image_width}rem * {width} / {native_width});height:calc({image_height}rem * {height} / {native_height});
  --key-shape:polygon({polygon});--key-focus:url('./assets/{filename}');
}}""")
    return "\n".join(rules), assets


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify checked-in outputs without writing.")
    args = parser.parse_args()
    portrait, assets = export("portrait")
    wide, wide_assets = export("wide")
    assets.update(wide_assets)
    css = f"""{START}
/* Generated by tools/handset-controls.py from the final native key masks. */
.stream-dock{{position:static;display:block;padding:0}}
.dock-button{{position:absolute;display:block;padding:0;clip-path:var(--key-shape);outline:none;isolation:isolate}}
.dock-button::before,.dock-button::after{{content:'';position:absolute;inset:0;pointer-events:none;opacity:0}}
.dock-button::before{{background:linear-gradient(110deg,#fff7da12,#fff7da05)}}
.dock-button::after{{background:var(--key-focus) center/100% 100% no-repeat;image-rendering:pixelated}}
@media(hover:hover){{.dock-button:hover::before{{opacity:1}}}}
.dock-button:active::before{{opacity:1;background:linear-gradient(180deg,#080a08a6 0,#080a084d 18%,#080a0826 72%,#e3ddca08);box-shadow:inset 0 4rem 4rem #0005}}
.dock-button:focus-visible::after{{opacity:1}}
{portrait}
@media(max-height:550px) and (min-width:600px){{
{wide}
}}
{END}"""
    stylesheet = ROOT / "physical-shell.css"
    current = stylesheet.read_text()
    if START in current:
        before, rest = current.split(START, 1)
        _, after = rest.split(END, 1)
        updated = before + css + after
    else:
        updated = current.rstrip() + "\n" + css + "\n"
    assets[stylesheet] = updated
    for path, content in assets.items():
        if args.check:
            assert path.read_text() == content, f"Regenerate handset controls: {path}"
        else:
            path.write_text(content)
    print("Handset control CSS and six native focus rings are current.")


if __name__ == "__main__":
    main()
